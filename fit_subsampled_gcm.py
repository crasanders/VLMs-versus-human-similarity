def load_categorization_data(
    prob_path: Path = PROB_FILE,
    train_path: Path = TRAIN_FILE,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Load 120x10 classification probabilities/frequencies and 30 training exemplars."""
    prob_raw = np.loadtxt(prob_path)
    if prob_raw.shape != (N_IGNEOUS, 2 + N_CATEGORIES):
        raise ValueError(f"Expected shape {(N_IGNEOUS, 2 + N_CATEGORIES)} in {prob_path}, got {prob_raw.shape}")
    probs = prob_raw[:, 2:].astype(float)

    with train_path.open("r", encoding="utf-8") as fh:
        lines = [line.strip() for line in fh if line.strip()]
    if len(lines) < 4:
        raise ValueError(f"Expected at least 4 lines in {train_path}, found {len(lines)}")

    n_subj = int(lines[0])
    cats = [int(tok) for tok in lines[1].split()]
    if cats != list(range(1, N_CATEGORIES + 1)):
        raise ValueError(f"Unexpected category header {cats} in {train_path}")

    train_rocks_1based = np.array([int(tok) for tok in lines[2].split()], dtype=int)
    train_cats_1based = np.array([int(tok) for tok in lines[3].split()], dtype=int)
    if len(train_rocks_1based) != len(train_cats_1based):
        raise ValueError("Mismatched training rock and category lengths in traincoverage.dat")

    train_idx = train_rocks_1based - 1
    train_cats = train_cats_1based - 1
    if np.any((train_idx < 0) | (train_idx >= N_IGNEOUS)):
        raise ValueError("Training rock index out of [0, 119] range")
    if np.any((train_cats < 0) | (train_cats >= N_CATEGORIES)):
        raise ValueError("Training category index out of [0, 9] range")

    n_per_rock = TRIALS_PER_SUBJECT * n_subj
    freqs = np.rint(probs * n_per_rock).astype(int)
    if not np.all(freqs.sum(axis=1) == n_per_rock):
        raise ValueError("Reconstructed frequencies do not sum to 3 * n_subj per rock")
    if int(freqs.sum()) != N_IGNEOUS * n_per_rock:
        raise ValueError(f"Unexpected total trial count {freqs.sum()}")

    m_cat = np.zeros((len(train_idx), N_CATEGORIES), dtype=float)
    m_cat[np.arange(len(train_idx)), train_cats] = 1.0
    return probs, freqs, train_idx, m_cat


def load_igneous_rock_ids(table_path: Path = ROCKS_TABLE_PATH) -> list[str]:
    """Return the ordered 120 Igneous rock IDs from 360_rocks_table.csv."""
    table = pd.read_csv(table_path, index_col=0).iloc[:N_IGNEOUS]
    if len(table) != N_IGNEOUS or not (table["Category"] == "Igneous").all():
        raise ValueError(f"First {N_IGNEOUS} rows of {table_path} must all belong to Igneous")
    return [f"{row.Category[0]}_{row.Subtype}_{int(row.Token):02d}" for row in table.itertuples()]


def _gcm_probabilities(
    dist_mat: np.ndarray,
    m_cat: np.ndarray,
    gamma: float,
    eps: float,
) -> np.ndarray:
    """Compute GCM response probabilities P(J | i) from scaled distances."""
    sim = np.exp(-dist_mat)
    cat_sim = sim @ m_cat
    log_cs = gamma * np.log(np.maximum(cat_sim, 1e-300))
    log_cs -= log_cs.max(axis=1, keepdims=True)
    weights = np.exp(log_cs)
    probs_pred = (1.0 - eps) * (weights / weights.sum(axis=1, keepdims=True)) + eps / N_CATEGORIES
    return np.clip(probs_pred, 1e-15, 1.0)


def _compute_metrics(
    pred_probs: np.ndarray,
    obs_probs: np.ndarray,
    obs_freqs: np.ndarray,
    n_params: int,
) -> dict[str, float]:
    """Compute -ln L, BIC, %Var, Pearson r, and RMSE for a fitted GCM."""
    neg_ll = -float(np.sum(obs_freqs * np.log(pred_probs)))
    n_tot = float(obs_freqs.sum())
    bic = 2.0 * neg_ll + float(n_params) * float(np.log(n_tot))
    sse = float(np.sum((pred_probs - obs_probs) ** 2))
    sst = float(np.sum((obs_probs - obs_probs.mean()) ** 2))
    pct_var = 100.0 * (1.0 - sse / sst)
    pearson_r = float(np.corrcoef(pred_probs.ravel(), obs_probs.ravel())[0, 1])
    rmse = float(np.sqrt(np.mean((pred_probs - obs_probs) ** 2)))
    return {
        "neg_ln_L": neg_ll,
        "BIC": bic,
        "pct_var": pct_var,
        "pearson_r": pearson_r,
        "rmse": rmse,
    }


def fit_core_gcm(
    coords_120: np.ndarray,
    obs_probs: np.ndarray,
    obs_freqs: np.ndarray,
    train_idx: np.ndarray,
    m_cat: np.ndarray,
) -> dict[str, float]:
    """Fit Core GCM (P=3: c, gamma, eps) using unweighted 8D Euclidean distances."""
    dist_raw = np.sqrt(np.sum((coords_120[:, None, :] - coords_120[train_idx][None, :, :]) ** 2, axis=-1))
    d_scale = float(np.mean(dist_raw[dist_raw > 0]))
    dist_norm = dist_raw / d_scale

    def objective(theta: np.ndarray) -> float:
        c_norm, gamma, eps = theta
        if c_norm <= 0.0 or gamma <= 0.0 or not (0.0 <= eps <= 1.0):
            return 1e12
        pred = _gcm_probabilities(c_norm * dist_norm, m_cat, gamma, eps)
        return -float(np.sum(obs_freqs * np.log(pred)))

    starts = [
        np.array([c0, g0, 0.02], dtype=float)
        for c0 in (1.0, 4.0, 10.0)
        for g0 in (0.5, 2.0, 5.0)
    ]
    bounds = [(1e-4, 100.0), (1e-3, 50.0), (0.0, 0.99)]

    best_x: np.ndarray | None = None
    best_fun = np.inf
    for x0 in starts:
        res = minimize(objective, x0, method="L-BFGS-B", bounds=bounds, options={"ftol": 1e-12, "maxiter": 1000})
        if res.fun < best_fun:
            best_fun = float(res.fun)
            best_x = res.x.copy()

    assert best_x is not None
    res_nm = minimize(
        objective,
        best_x,
        method="Nelder-Mead",
        options={"xatol": 1e-10, "fatol": 1e-10, "maxiter": 5000},
    )
    if res_nm.fun < best_fun:
        best_x = res_nm.x.copy()

    c_norm, gamma, eps = float(best_x[0]), float(best_x[1]), float(best_x[2])
    pred = _gcm_probabilities(c_norm * dist_norm, m_cat, gamma, eps)
    metrics = _compute_metrics(pred, obs_probs, obs_freqs, n_params=3)
    return {
        "gcm_model": "core",
        "n_params": 3,
        **metrics,
        "c": c_norm / d_scale,
        "c_norm": c_norm,
        "d_scale": d_scale,
        "gamma": gamma,
        "eps": eps,
        **{f"w{d + 1}": 1.0 / N_DIMENSIONS for d in range(N_DIMENSIONS)},
    }


def fit_weighted_8d_gcm(
    coords_120: np.ndarray,
    obs_probs: np.ndarray,
    obs_freqs: np.ndarray,
    train_idx: np.ndarray,
    m_cat: np.ndarray,
    core_fit: dict[str, float],
    seed: int = 0,
) -> dict[str, float]:
    """Fit Weighted 8D GCM (P=10: c, w1..w8 summing to 1, gamma, eps), seeded from Core GCM."""
    diff_sq = (coords_120[:, None, :] - coords_120[train_idx][None, :, :]) ** 2
    dist_raw = np.sqrt(np.sum(diff_sq, axis=-1))
    d_scale = float(np.mean(dist_raw[dist_raw > 0]))
    diff_sq_norm = diff_sq / (d_scale ** 2)

    def objective(theta: np.ndarray) -> float:
        a = theta[:N_DIMENSIONS]
        gamma, eps = float(theta[N_DIMENSIONS]), float(theta[N_DIMENSIONS + 1])
        dist_scaled = np.sqrt(np.maximum(np.tensordot(diff_sq_norm, a, axes=([-1], [0])), 0.0))
        pred = _gcm_probabilities(dist_scaled, m_cat, gamma, eps)
        return -float(np.sum(obs_freqs * np.log(pred)))

    # Seed #0: exact nested Core GCM optimum (a_m = c_norm_core^2 for all m yields identical distances)
    a_core = float(np.clip(core_fit["c_norm"] ** 2, 0.0, 1000.0))
    gamma_core = float(np.clip(core_fit["gamma"], 1e-3, 50.0))
    eps_core = float(np.clip(core_fit["eps"], 0.0, 0.99))

    starts = [
        np.array([a_core] * N_DIMENSIONS + [gamma_core, eps_core], dtype=float),
        np.array([1.0] * N_DIMENSIONS + [2.0, 0.02], dtype=float),
        np.array([5.0] * N_DIMENSIONS + [2.0, 0.02], dtype=float),
    ]
    rng = np.random.default_rng(seed)
    for _ in range(5):
        starts.append(
            np.concatenate(
                [
                    rng.uniform(0.5, 15.0, size=N_DIMENSIONS),
                    [rng.uniform(0.5, 5.0), rng.uniform(0.005, 0.08)],
                ]
            )
        )

    bounds = [(0.0, 1000.0)] * N_DIMENSIONS + [(1e-3, 50.0), (0.0, 0.99)]
    best_x: np.ndarray | None = None
    best_fun = np.inf
    for x0 in starts:
        res = minimize(objective, x0, method="L-BFGS-B", bounds=bounds, options={"ftol": 1e-12, "maxiter": 1000})
        if res.fun < best_fun:
            best_fun = float(res.fun)
            best_x = res.x.copy()

    assert best_x is not None
    a_opt = np.clip(best_x[:N_DIMENSIONS], 0.0, None)
    gamma = float(best_x[N_DIMENSIONS])
    eps = float(best_x[N_DIMENSIONS + 1])

    dist_scaled = np.sqrt(np.maximum(np.tensordot(diff_sq_norm, a_opt, axes=([-1], [0])), 0.0))
    pred = _gcm_probabilities(dist_scaled, m_cat, gamma, eps)
    metrics = _compute_metrics(pred, obs_probs, obs_freqs, n_params=10)

    if metrics["neg_ln_L"] > core_fit["neg_ln_L"] + 1e-3:
        raise AssertionError(
            f"Weighted 8D GCM ({metrics['neg_ln_L']:.4f}) failed nesting invariant vs. "
            f"Core GCM ({core_fit['neg_ln_L']:.4f})"
        )

    a_sum = float(a_opt.sum())
    weights = a_opt / a_sum if a_sum > 1e-12 else np.full(N_DIMENSIONS, 1.0 / N_DIMENSIONS)
    c_opt = float(np.sqrt(a_sum)) / d_scale

    return {
        "gcm_model": "weighted8d",
        "n_params": 10,
        **metrics,
        "c": c_opt,
        "c_norm": float(np.sqrt(a_sum)),
        "d_scale": d_scale,
        "gamma": gamma,
        "eps": eps,
        **{f"w{d + 1}": float(weights[d]) for d in range(N_DIMENSIONS)},
    }


def fit_single_mds_row(
    row_meta: dict,
    expected_rock_ids: list[str],
    probs: np.ndarray,
    freqs: np.ndarray,
    train_idx: np.ndarray,
    m_cat: np.ndarray,
    base_seed: int,
) -> list[dict]:
    """Load one saved MDS CSV, assert rock alignment, and fit both Core and Weighted 8D GCM."""
    mds_path = Path(row_meta["mds_file"])
    mds_df = pd.read_csv(mds_path, index_col="Rock").iloc[:N_IGNEOUS]
    if list(mds_df.index) != expected_rock_ids:
        raise ValueError(f"Rock ID mismatch in {mds_path}")

    coords_120 = mds_df[[f"Dim {d + 1}" for d in range(N_DIMENSIONS)]].to_numpy(dtype=float)
    core_res = fit_core_gcm(coords_120, probs, freqs, train_idx, m_cat)
    weighted_seed = int(np.random.SeedSequence([base_seed, int(row_meta["pct"]), int(row_meta["rep"])]).generate_state(1)[0])
    weighted_res = fit_weighted_8d_gcm(coords_120, probs, freqs, train_idx, m_cat, core_fit=core_res, seed=weighted_seed)

    shared_meta = {
        "mds_mode": row_meta["mds_mode"],
        "pct": int(row_meta["pct"]),
        "rep": int(row_meta["rep"]),
        "n_ratings": int(row_meta["n_ratings"]),
        "n_filled_pairs": int(row_meta["n_filled_pairs"]),
        "pct_filled_pairs": float(row_meta["pct_filled_pairs"]),
        "stress1_objective": float(row_meta["stress1_objective"]),
        "dist_r_vs_published_human": float(row_meta["dist_r_vs_published_human"]),
        "mean_r_dims1_6": float(row_meta["mean_r_dims1_6"]),
        "mds_file": str(row_meta["mds_file"]),
    }
    return [{**shared_meta, **core_res}, {**shared_meta, **weighted_res}]


def compute_benchmarks(
    probs: np.ndarray,
    freqs: np.ndarray,
    train_idx: np.ndarray,
    m_cat: np.ndarray,
    seed: int,
) -> pd.DataFrame:
    """Recompute Core & Weighted 8D GCM benchmarks and verify Table 2 reproduction."""
    sources = [
        ("Human MDS (published 8D)", PUBLISHED_HUMAN_MDS_PATH, {"neg_ln_L": 14559.2, "BIC": 29146.9, "pct_var": 83.5}),
        ("GPT-4o (encourage middle)", GPT4O_ENCOURAGE_MDS_PATH, {"neg_ln_L": 13552.8, "BIC": 27134.3, "pct_var": 89.5}),
        ("GPT-4o (baseline)", GPT4O_BASELINE_MDS_PATH, {"neg_ln_L": 13621.2, "BIC": 27271.0, "pct_var": 89.1}),
    ]
    rows = []
    for label, path, expected in sources:
        coords_120 = np.loadtxt(path)[:N_IGNEOUS]
        core = fit_core_gcm(coords_120, probs, freqs, train_idx, m_cat)
        if (
            abs(core["neg_ln_L"] - expected["neg_ln_L"]) > 0.5
            or abs(core["BIC"] - expected["BIC"]) > 0.5
            or abs(core["pct_var"] - expected["pct_var"]) > 0.15
        ):
            raise AssertionError(
                f"Benchmark {label} deviated from Table 2: got -lnL={core['neg_ln_L']:.2f}, "
                f"BIC={core['BIC']:.2f}, %Var={core['pct_var']:.2f} vs expected {expected}"
            )
        weighted = fit_weighted_8d_gcm(coords_120, probs, freqs, train_idx, m_cat, core_fit=core, seed=seed)
        rows.append({"model": label, "source": "recomputed", "mds_file": path.as_posix(), **core})
        rows.append({"model": label, "source": "recomputed", "mds_file": path.as_posix(), **weighted})

    for item in TABLE2_CORE_BENCHMARKS:
        if item["model"].startswith(("Human", "GPT-4o")):
            continue
        rows.append(
            {
                "model": item["model"],
                "source": "paper_table2",
                "mds_file": "2510.20859v1.pdf (Table 2)",
                "gcm_model": "core",
                "n_params": 3,
                "neg_ln_L": item["neg_ln_L"],
                "BIC": item["BIC"],
                "pct_var": item["pct_var"],
            }
        )
    return pd.DataFrame(rows)


def _format_thousands(x: float, _pos: int) -> str:
    return f"{int(round(x)):,}"


def _plot_curve(
    ax: plt.Axes,
    df: pd.DataFrame,
    metric_col: str,
    color: str,
    label: str,
    rng_jitter: np.random.Generator,
    marker: str = "o",
) -> None:
    """Plot replicate dots, mean curve, and +-1 SD shaded band across percentages."""
    pcts = np.sort(df["pct"].unique())
    means = np.array([df.loc[df["pct"] == p, metric_col].mean() for p in pcts])
    stds = np.array([df.loc[df["pct"] == p, metric_col].std(ddof=1) for p in pcts])

    jitter = rng_jitter.uniform(-1.1, 1.1, size=len(df))
    ax.scatter(
        df["pct"].to_numpy() + jitter,
        df[metric_col].to_numpy(),
        s=18,
        color=color,
        alpha=0.30,
        edgecolors="none",
        zorder=2,
    )
    ax.fill_between(pcts, means - stds, means + stds, color=color, alpha=0.16, zorder=3)
    ax.plot(
        pcts,
        means,
        color=color,
        linewidth=2.3,
        marker=marker,
        markersize=5.5,
        markeredgecolor=SURFACE,
        markeredgewidth=0.8,
        label=label,
        zorder=4,
    )


def _finish_axis(ax: plt.Axes, ylabel: str, title: str, is_bic: bool = False) -> None:
    style_axes(ax)
    ax.set_xticks(list(range(10, 101, 10)))
    ax.set_xlim(4, 106)
    ax.set_xlabel("% of Human Similarity Data", fontsize=10)
    ax.set_ylabel(ylabel, fontsize=10.5)
    ax.set_title(title, loc="left", fontsize=11.5, fontweight="bold")
    if is_bic:
        ax.yaxis.set_major_formatter(FuncFormatter(_format_thousands))


