def format_summary_table(fits_df: pd.DataFrame) -> pd.DataFrame:
    """Compute per-(gcm_model, mds_mode, pct) mean and SD summary table."""
    cols = [
        "n_filled_pairs",
        "pct_filled_pairs",
        "BIC",
        "pct_var",
        "neg_ln_L",
        "pearson_r",
        "rmse",
        "dist_r_vs_published_human",
        "mean_r_dims1_6",
    ]
    rows = []
    for (gcm_model, mds_mode, pct), grp in fits_df.groupby(["gcm_model", "mds_mode", "pct"], sort=True):
        row: dict[str, object] = {
            "gcm_model": gcm_model,
            "mds_mode": mds_mode,
            "pct": int(pct),
            "n_reps": len(grp),
        }
        for col in cols:
            row[f"{col}_mean"] = float(grp[col].mean())
            row[f"{col}_sd"] = float(grp[col].std(ddof=1)) if len(grp) > 1 else 0.0
        rows.append(row)
    return pd.DataFrame(rows)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--subsampling-dir", type=Path, default=DEFAULT_SUBSAMPLING_DIR, help=f"Subsampling output root (default: {DEFAULT_SUBSAMPLING_DIR})")
    parser.add_argument("--n-jobs", type=int, default=-1, help="Number of joblib parallel workers (default: -1)")
    parser.add_argument("--seed", type=int, default=42, help="Base seed for Weighted 8D random restarts (default: 42)")
    parser.add_argument("--replot-only", action="store_true", help="Regenerate plots from existing CSVs without refitting GCM")
    parser.add_argument("--only-missing", action="store_true", help="Fit only MDS rows missing from gcm_fits_all.csv and merge")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    gcm_dir = args.subsampling_dir / "gcm"
    plots_dir = gcm_dir / "plots"
    fits_csv = gcm_dir / "gcm_fits_all.csv"
    bench_csv = gcm_dir / "gcm_benchmarks.csv"
    summary_csv = gcm_dir / "gcm_summary_by_pct.csv"
    gcm_dir.mkdir(parents=True, exist_ok=True)

    if args.replot_only:
        fits_df = pd.read_csv(fits_csv)
        bench_df = pd.read_csv(bench_csv)
        generate_plots(fits_df, bench_df, plots_dir)
        print(f"Regenerated 4 plot pairs from cached CSVs in {plots_dir}")
        return

    t0 = time.perf_counter()
    probs, freqs, train_idx, m_cat = load_categorization_data()
    expected_rock_ids = load_igneous_rock_ids()

    print("Evaluating and verifying Table 2 GCM benchmarks...")
    bench_df = compute_benchmarks(probs, freqs, train_idx, m_cat, seed=args.seed)
    bench_df.to_csv(bench_csv, index=False)
    print(
        bench_df[["model", "gcm_model", "n_params", "neg_ln_L", "BIC", "pct_var", "source"]]
        .round({"neg_ln_L": 1, "BIC": 1, "pct_var": 2})
        .to_string(index=False)
    )

    mds_summary_df = pd.read_csv(args.subsampling_dir / "summary_all.csv")
    existing_fits_df = pd.read_csv(fits_csv) if (args.only_missing and fits_csv.exists()) else None
    if existing_fits_df is not None:
        done_keys = set(
            zip(existing_fits_df["mds_mode"], existing_fits_df["pct"].astype(int), existing_fits_df["rep"].astype(int))
        )
        meta_rows = [
            row
            for row in mds_summary_df.to_dict(orient="records")
            if (row["mds_mode"], int(row["pct"]), int(row["rep"])) not in done_keys
        ]
    else:
        meta_rows = mds_summary_df.to_dict(orient="records")
    print(f"\nFitting Core (P=3) and Weighted 8D (P=10) GCM across {len(meta_rows)} MDS spaces (n_jobs={args.n_jobs})...")

    nested_results = Parallel(n_jobs=args.n_jobs)(
        delayed(fit_single_mds_row)(
            row_meta=row,
            expected_rock_ids=expected_rock_ids,
            probs=probs,
            freqs=freqs,
            train_idx=train_idx,
            m_cat=m_cat,
            base_seed=args.seed,
        )
        for row in meta_rows
    )
    flat_rows = [item for pair in nested_results for item in pair]
    new_fits_df = pd.DataFrame(flat_rows)
    if existing_fits_df is not None and not new_fits_df.empty:
        fits_df = pd.concat([existing_fits_df, new_fits_df], ignore_index=True)
    elif existing_fits_df is not None:
        fits_df = existing_fits_df
    else:
        fits_df = new_fits_df
    fits_df = fits_df.sort_values(["gcm_model", "mds_mode", "pct", "rep"]).reset_index(drop=True)
    fits_df.to_csv(fits_csv, index=False)

    summary_df = format_summary_table(fits_df)
    summary_df.to_csv(summary_csv, index=False)

    generate_plots(fits_df, bench_df, plots_dir)

    print(f"\nCompleted {len(fits_df)} GCM fits in {time.perf_counter() - t0:.1f}s.")
    print("\nSummary by (gcm_model, mds_mode, pct):")
    print(
        summary_df[
            ["gcm_model", "mds_mode", "pct", "BIC_mean", "BIC_sd", "pct_var_mean", "pct_var_sd", "neg_ln_L_mean"]
        ]
        .round({"BIC_mean": 1, "BIC_sd": 1, "pct_var_mean": 2, "pct_var_sd": 2, "neg_ln_L_mean": 1})
        .to_string(index=False)
    )
    print(f"\nSaved CSVs to {gcm_dir} and plots to {plots_dir}")


if __name__ == "__main__":
    main()
